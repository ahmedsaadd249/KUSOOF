#!/usr/bin/env node
/* ==========================================================================
   write-env — copies the PUBLIC values from .env into js/env.public.js so the
   static site (no build step) can read them.

     node scripts/write-env.mjs

   Only the names in PUBLIC are ever written. Secrets (service role key,
   Brevo keys, SMTP key) are never copied, and the script fails if a public
   value looks like a secret (e.g. a service_role JWT pasted by mistake).
   ========================================================================== */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, '.env');
const outPath = join(root, 'js', 'env.public.js');

const REQUIRED = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'APP_URL'];
const OPTIONAL = ['GOOGLE_MAPS_API_KEY', 'GOOGLE_MAPS_MAP_ID'];
const PUBLIC = [...REQUIRED, ...OPTIONAL];

function parse(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i === -1) continue;
    const key = line.slice(0, i).trim();
    let value = line.slice(i + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    out[key] = value;
  }
  return out;
}

function jwtRole(token) {
  try {
    const payload = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8'));
    return payload.role || null;
  } catch {
    return null;
  }
}

if (!existsSync(envPath)) {
  console.error('✗ .env not found. Copy .env.example to .env and fill it in.');
  process.exit(1);
}

const env = parse(readFileSync(envPath, 'utf8'));
const missing = REQUIRED.filter((k) => !env[k]);
if (missing.length) {
  console.error(`✗ Missing required values in .env: ${missing.join(', ')}`);
  process.exit(1);
}

// Guard: never let a secret reach the browser
const anonRole = env.SUPABASE_ANON_KEY.startsWith('eyJ') ? jwtRole(env.SUPABASE_ANON_KEY) : null;
if (anonRole && anonRole !== 'anon') {
  console.error(`✗ SUPABASE_ANON_KEY has role "${anonRole}". That is a secret key — use the public anon key.`);
  process.exit(1);
}
if (/^sb_secret_/.test(env.SUPABASE_ANON_KEY)) {
  console.error('✗ SUPABASE_ANON_KEY is a secret key (sb_secret_…). Use the public anon/publishable key.');
  process.exit(1);
}
const secretValues = ['SUPABASE_SERVICE_ROLE_KEY', 'BREVO_API_KEY', 'BREVO_SMTP_KEY'].map((k) => env[k]).filter(Boolean);
for (const k of PUBLIC) {
  if (env[k] && secretValues.includes(env[k])) {
    console.error(`✗ ${k} has the same value as a secret. Refusing to write it to the browser.`);
    process.exit(1);
  }
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(env.SUPABASE_URL)) {
  console.warn(`! SUPABASE_URL looks unusual: ${env.SUPABASE_URL}`);
}

const values = Object.fromEntries(PUBLIC.map((k) => [k, (env[k] || '').replace(/\/$/, k === 'SUPABASE_URL' || k === 'APP_URL' ? '' : '$&')]));
const file = `/* Generated by scripts/write-env.mjs from .env — public values only. Do not edit; do not commit. */
export const ENV = Object.freeze(${JSON.stringify(values, null, 2)});
`;
writeFileSync(outPath, file);
console.log(`✓ Wrote js/env.public.js (${PUBLIC.filter((k) => values[k]).join(', ')})`);
const unset = OPTIONAL.filter((k) => !values[k]);
if (unset.length) console.log(`  Not set yet (features show a setup message): ${unset.join(', ')}`);
