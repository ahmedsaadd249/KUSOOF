#!/usr/bin/env node
/* ==========================================================================
   build — production bundle for static hosting (Cloudflare Pages).

     node scripts/build.mjs        →  dist/

   No framework and no dependencies: the site is plain HTML / CSS / ES
   modules. The build only
     1. copies the website files into dist/ (never docs/, scripts/,
        supabase/, .env, videos/ …), and
     2. writes dist/js/env.public.js with the PUBLIC configuration.

   Configuration comes from environment variables (Cloudflare Pages ›
   Settings › Variables) or, locally, from .env. Only these names are ever
   written to the browser: SUPABASE_URL, SUPABASE_ANON_KEY, APP_URL,
   GOOGLE_MAPS_API_KEY, GOOGLE_MAPS_MAP_ID. The build fails if a secret
   key is supplied in their place.
   ========================================================================== */
import { readFileSync, writeFileSync, existsSync, rmSync, mkdirSync, cpSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist');

/* ---------- configuration ---------- */
function readDotEnv() {
  const file = join(root, '.env');
  if (!existsSync(file)) return {};
  const env = {};
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || !line.includes('=')) continue;
    const i = line.indexOf('=');
    let v = line.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    env[line.slice(0, i).trim()] = v;
  }
  return env;
}
const dotenv = readDotEnv();
const get = (name) => (process.env[name] ?? dotenv[name] ?? '').trim();

const PUBLIC = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'APP_URL', 'GOOGLE_MAPS_API_KEY', 'GOOGLE_MAPS_MAP_ID'];
const config = Object.fromEntries(PUBLIC.map((k) => [k, get(k)]));
config.SUPABASE_URL = config.SUPABASE_URL.replace(/\/$/, '');
config.APP_URL = (config.APP_URL || process.env.CF_PAGES_URL || '').replace(/\/$/, '');

const fail = (msg) => {
  console.error(`✗ Build stopped: ${msg}`);
  process.exit(1);
};
if (!config.SUPABASE_URL || !config.SUPABASE_ANON_KEY) fail('SUPABASE_URL and SUPABASE_ANON_KEY must be set (Cloudflare › Settings › Variables, or .env locally).');
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(config.SUPABASE_URL)) fail('SUPABASE_URL must look like https://<ref>.supabase.co');

// Never let a secret reach the browser
const jwtRole = (t) => {
  try {
    return JSON.parse(Buffer.from(t.split('.')[1], 'base64url').toString('utf8')).role || null;
  } catch {
    return null;
  }
};
if (/^sb_secret_/.test(config.SUPABASE_ANON_KEY)) fail('SUPABASE_ANON_KEY is a secret key (sb_secret_…). Use the public anon / publishable key.');
if (config.SUPABASE_ANON_KEY.startsWith('eyJ') && jwtRole(config.SUPABASE_ANON_KEY) !== 'anon') fail('SUPABASE_ANON_KEY is not the public anon key (wrong JWT role).');
const secrets = ['SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_ACCESS_TOKEN', 'BREVO_API_KEY', 'BREVO_SMTP_KEY'].map(get).filter(Boolean);
for (const k of PUBLIC) if (config[k] && secrets.includes(config[k])) fail(`${k} has the same value as a secret.`);
for (const k of PUBLIC) if (/^(xkeysib-|xsmtpsib-|sbp_)/.test(config[k])) fail(`${k} looks like a Brevo key or access token.`);

/* ---------- copy the website ---------- */
const SITE_FILES = ['index.html', 'products.html', 'product.html', 'cart.html', 'checkout.html', 'account.html', 'verify.html', 'order-confirmation.html', 'rate.html'];
const SITE_DIRS = ['css', 'js', 'frames', 'products', 'logo', 'admin'];

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const f of SITE_FILES) {
  if (!existsSync(join(root, f))) fail(`missing ${f}`);
  cpSync(join(root, f), join(out, f));
}
for (const d of SITE_DIRS) {
  if (!existsSync(join(root, d))) fail(`missing ${d}/`);
  cpSync(join(root, d), join(out, d), {
    recursive: true,
    filter: (src) => !/env\.public\.js$/.test(src) && !/\.(map|md)$/.test(src),
  });
}

// Browsers ask for /favicon.ico even when the page declares an icon
cpSync(join(root, 'logo', 'kusoof-icon.png'), join(out, 'favicon.ico'));

/* ---------- public configuration ---------- */
writeFileSync(
  join(out, 'js', 'env.public.js'),
  `/* Generated by scripts/build.mjs — public values only. */\nexport const ENV = Object.freeze(${JSON.stringify(config, null, 2)});\n`
);

/* ---------- Cloudflare Pages headers ---------- */
writeFileSync(
  join(out, '_headers'),
  `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Permissions-Policy: geolocation=(self), camera=(), microphone=(), payment=()

/admin/*
  X-Robots-Tag: noindex, nofollow

/frames/*
  Cache-Control: public, max-age=604800

/products/*
  Cache-Control: public, max-age=604800

/logo/*
  Cache-Control: public, max-age=604800
`
);

/* ---------- summary ---------- */
let files = 0;
let bytes = 0;
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) walk(p);
    else {
      files += 1;
      bytes += s.size;
    }
  }
};
walk(out);
console.log(`✓ Built dist/ — ${files} files, ${(bytes / 1024 / 1024).toFixed(1)} MB`);
console.log(`  Supabase:    ${config.SUPABASE_URL}`);
console.log(`  App URL:     ${config.APP_URL || '(not set)'}`);
console.log(`  Google Maps: ${config.GOOGLE_MAPS_API_KEY ? 'key set' : 'not set — the map shows its setup message'}${config.GOOGLE_MAPS_MAP_ID ? ', Map ID set' : ''}`);
